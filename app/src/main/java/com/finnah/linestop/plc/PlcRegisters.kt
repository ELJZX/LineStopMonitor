package com.finnah.linestop.plc

/**
 * Карта регистров контроллера DVP12SE11R, совместимая с ладдер-программой
 * заказчика (файл plc/DVP12SE11R_LineStop.md).
 *
 * Программа ПЛК:
 *   X0 = сигнал аварии (уровень): 1 = авария, 0 = линия работает.
 *   M1002 (первый скан) -> D0 = 0, D1 = 0
 *   X0 = 1              -> D0 = 1
 *   X0 = 0              -> D0 = 0
 *   X0 (спад)           -> INC D1                  ; счётчик запусков
 *   D101 = 1            -> D5 = D100, INC D4, D101 = 0, D100 = 0
 *
 * В Modbus TCP адрес регистра Dn = 0x1000 + n.
 */
object PlcRegisters {

    /** D0: состояние сигнала аварии. 0 = линия работает, 1 = авария. */
    const val STATE = 0

    /** D1: счётчик запусков (инкремент по спаду X0). */
    const val START_COUNTER = 1

    /** D4: счётчик квитирований (инкремент, когда приложение подтвердило причину). */
    const val ACK_COUNTER = 4

    /** D5: код последней подтверждённой причины. */
    const val LAST_CAUSE = 5

    /** D100: код причины от приложения (1..10, 99 = другая). */
    const val CAUSE_CODE = 100

    /** D101: флаг запроса квитирования: приложение пишет 1, ПЛК сбрасывает в 0. */
    const val ACK_REQUEST = 101

    /** Базовый Modbus-адрес регистров D. */
    const val MODBUS_D_BASE = 0x1000

    /** Преобразование номера D-регистра в Modbus-адрес. */
    fun d(register: Int): Int = MODBUS_D_BASE + register
}
